static uint32_t next(const unsigned char **p)
{
 unsigned char a=*(*p)++; if(a<128) return a;
 int n=a>=0xc2 && a<0xe0 ? 1:a<0xf0 && a>=0xe0 ? 2:a>=0xf0 && a<0xf5 ? 3:0;
 if(!n) return a;
 uint32_t cp=a&((1u<<(6-n))-1);
 for(int i=0;i<n;i++) { unsigned char b=**p; if((b&0xc0)!=0x80) return a; (*p)++; cp=(cp<<6)|(b&63); }
 return cp;
}
